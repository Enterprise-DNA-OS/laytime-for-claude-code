import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { minute, cents } from './calculate.mjs';

export function parseStatement(text) {
 const flat=text.replace(/\s+/g,' ').trim();
 if(!flat.includes('Laytime Statement')||!flat.includes('Layline'))throw Error('Not a supported Layline statement');
 const take=(re,label)=>{const m=flat.match(re);if(!m)throw Error(`Statement missing ${label}; use the original text PDF export`);return m;};
 const vessel=take(/\bVessel\s+(.+?)\s+Port\s+(.+?)\s+IMO\b/,'vessel and port');
 const demurrage=take(/Demurrage rate\s*\$([\d,.]+)\s*\/\s*day/,'demurrage rate')[1];
 const dispatch=flat.match(/Despatch rate\s*\$([\d,.]+)\s*\/\s*day/);
 const hours=take(/Allowed laytime\s+([\d.]+)\s*h\b/,'allowed hours')[1];
 const allowed=Number(hours)*60;if(!Number.isSafeInteger(allowed))throw Error('Allowed hours must resolve to whole minutes');
 const eventCount=Number(take(/\bEvents\s+(\d+)\b/,'event count')[1]);
 const section=take(/Statement of facts\s+(.+?)(?:\bComputation\b|Generated by Layline)/,'event section')[1];
 const rows=[...section.matchAll(/(\S+)\s+(\d{4}-\d\d-\d\d)\s+(\d\d:\d\d)\s+UTC\s+(.+?)\s+(Yes|No)\s+(\d+(?:\.\d+)?)\s*%/g)].map(m=>({source_key:m[1],occurred_at:`${m[2]}T${m[3]}:00Z`,description:m[4],counts:m[5]==='Yes',factor:m[6]}));
 if(!eventCount||rows.length!==eventCount)throw Error(`Event reconciliation failed: parsed ${rows.length}, expected ${eventCount}`);
 if(new Set(rows.map(r=>r.source_key)).size!==rows.length)throw Error('Duplicate source event identifiers');
 for(const e of rows){minute(e.occurred_at);if(Number(e.factor)<0||Number(e.factor)>100)throw Error('Unsupported source factor');}
 const mode=take(/Laytime type\s+(NON REVERSIBLE|NON_REVERSIBLE|REVERSIBLE|AVERAGE)/,'laytime type')[1];
 const weekend=take(/Weekend rule\s+(SHEX|SHINC|FHEX)/,'weekend rule')[1];
 return {vessel:vessel[1].trim(),port:vessel[2].trim(),allowed_minutes:allowed,demurrage_rate_cents:cents(demurrage.replaceAll(',','')),despatch_rate_cents:dispatch?cents(dispatch[1].replaceAll(',','')):null,source_laytime_type:mode,source_weekend_rule:weekend,events:rows};
}

export async function readStatement(file) {
 const stat=fs.statSync(file);if(stat.size>5*1024*1024)throw Error('Statement exceeds the 5 MB import limit');
 const bytes=fs.readFileSync(file);
 if(!bytes.subarray(0,5).equals(Buffer.from('%PDF-')))throw Error('Import expects a text-based PDF from the Layline Export button');
 const {getDocument}=await import('pdfjs-dist/legacy/build/pdf.mjs');
 const task=getDocument({data:new Uint8Array(bytes),isEvalSupported:false,useSystemFonts:false,disableFontFace:true,verbosity:0});
 let doc;const lines=[];
 try {
  doc=await task.promise;if(doc.numPages>30)throw Error('Statement exceeds 30 pages');
  for(let n=1;n<=doc.numPages;n++){
   const p=await doc.getPage(n),content=await p.getTextContent(),groups=[];
   for(const item of content.items){if(!('str' in item)||!item.str.trim())continue;const y=item.transform[5];let group=groups.find(g=>Math.abs(g.y-y)<2);if(!group){group={y,items:[]};groups.push(group);}group.items.push(item);}
   groups.sort((a,b)=>b.y-a.y);for(const g of groups)lines.push(g.items.sort((a,b)=>a.transform[4]-b.transform[4]).map(x=>x.str).join(' '));
  }
 } finally {await task.destroy();}
 const text=lines.join('\n');return {text,parsed:parseStatement(text),hash:createHash('sha256').update(bytes).digest('hex'),original_base64:bytes.toString('base64')};
}
